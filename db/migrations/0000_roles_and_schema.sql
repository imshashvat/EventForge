-- ── Roles ────────────────────────────────────────────────────────────────────
-- app_rw   : runtime application (INSERT, UPDATE, SELECT on app schema)
-- app_ro   : read-only (exports, reports — SELECT only)
-- migrator : runs migrations (owns schema objects)
-- These roles must exist before any other migrations run.

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'app_rw') THEN
    CREATE ROLE app_rw NOLOGIN;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'app_ro') THEN
    CREATE ROLE app_ro NOLOGIN;
  END IF;
END $$;

-- ── Schema ───────────────────────────────────────────────────────────────────
CREATE SCHEMA IF NOT EXISTS app;

-- Grant usage on schema to runtime roles
GRANT USAGE ON SCHEMA app TO app_rw;
GRANT USAGE ON SCHEMA app TO app_ro;

-- Future tables automatically get SELECT granted to app_ro
ALTER DEFAULT PRIVILEGES IN SCHEMA app
  GRANT SELECT ON TABLES TO app_ro;

-- Future tables automatically get full DML to app_rw
ALTER DEFAULT PRIVILEGES IN SCHEMA app
  GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO app_rw;

-- app_rw can use sequences (for UUIDs generated by the DB, if any)
ALTER DEFAULT PRIVILEGES IN SCHEMA app
  GRANT USAGE ON SEQUENCES TO app_rw;

-- ── Extensions ───────────────────────────────────────────────────────────────
-- uuid-ossp, pgcrypto, and pg_net are pre-installed on Supabase.
-- We create them only if not present to keep this migration idempotent.
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";
CREATE EXTENSION IF NOT EXISTS "pgcrypto";
-- pg_advisory_xact_lock is a built-in PG function — no extension needed.
